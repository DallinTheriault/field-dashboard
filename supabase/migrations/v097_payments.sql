-- v097: payments (billing slice 4). "Mark paid" stamped the time the button
-- was pressed and stored nothing else; the books need the real deposit date.
-- Each payment is a row; an invoice is paid when its payments reach its total,
-- dated by the last payment. A payment on a draft also sends it (some drafts
-- were paid outside Field).

-- 1. Payments ------------------------------------------------------------------
create table public.payments (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public."Clients" (id) on delete cascade,
  invoice_id bigint not null,
  -- The day the money came in, as a plain date: midnight UTC would show as
  -- the day before in Mountain time.
  received_on date not null,
  amount_cents integer not null check (amount_cents > 0),
  method text not null check (method in ('e_check', 'check', 'cash', 'card', 'other', 'unknown')),
  -- Check number, or the Stripe invoice id for a card payment.
  reference text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  constraint payments_invoice_same_tenant foreign key (client_id, invoice_id)
    references public.invoices (client_id, id) on delete restrict
);
create index payments_invoice_id_idx on public.payments (invoice_id);
create index payments_client_id_idx on public.payments (client_id);
-- Stripe retries webhook deliveries; the second insert is a no-op.
create unique index payments_card_reference_key on public.payments (reference)
  where method = 'card' and reference is not null;

alter table public.payments enable row level security;
create policy payments_select on public.payments for select to authenticated
  using (client_id in (select public.current_user_client_ids()));
create policy payments_insert on public.payments for insert to authenticated
  with check (public.user_can_write_client(client_id) and method <> 'card');
-- A mistyped payment can be removed. Card payments come from Stripe and stay.
create policy payments_delete on public.payments for delete to authenticated
  using (public.user_can_write_client(client_id) and method <> 'card');
revoke all on public.payments from public, anon, authenticated;
grant select, insert, delete on public.payments to authenticated;
grant all on public.payments to service_role;

-- 2. Existing paid invoices get one payment each, so the books stay consistent.
-- On prod that's exactly Sharpline's invoices 6 (paid through Stripe) and 11
-- (marked paid by hand), checked 2026-10-15 and approved by Dallin. paid_at is
-- unchanged (the triggers below don't exist yet). A Stripe-paid one is a card
-- payment with its Stripe id; the rest are method unknown.
insert into public.payments (client_id, invoice_id, received_on, amount_cents, method, reference, created_by)
select i.client_id, i.id,
       (i.paid_at at time zone coalesce(c.timezone, 'America/Denver'))::date,
       i.total_cents,
       case when i.stripe_invoice_id is not null then 'card' else 'unknown' end,
       i.stripe_invoice_id,
       null
  from public.invoices i
  join public."Clients" c on c.id = i.client_id
 where i.status = 'paid' and i.paid_at is not null and i.total_cents > 0;

-- 3. What a payment does ----------------------------------------------------------
-- Noon on the payment day in the tenant's timezone: the P&L groups income by
-- day there, and noon can't slip across midnight.
create function public.tenant_noon(p_client_id bigint, p_day date)
  returns timestamptz
  language sql
  stable
  set search_path = public
as $$
  select (p_day + time '12:00') at time zone coalesce(
    (select timezone from public."Clients" where id = p_client_id), 'America/Denver');
$$;
revoke execute on function public.tenant_noon(bigint, date) from public, anon;
grant execute on function public.tenant_noon(bigint, date) to authenticated, service_role;

-- People can't pay a void, overpay, or add to a paid invoice. Server code
-- (the Stripe webhook) records what Stripe says happened, whatever it is.
create function public.payments_guard()
  returns trigger
  language plpgsql
  set search_path = public
as $$
declare
  v_inv public.invoices%rowtype;
  v_paid bigint;
begin
  select * into v_inv from public.invoices where id = new.invoice_id for update;
  if auth.uid() is null then
    return new;
  end if;
  new.created_by := auth.uid();
  if v_inv.status = 'voided' then
    raise exception 'Invoice % is void; it can''t take a payment.', v_inv.invoice_number using errcode = '42501';
  end if;
  if v_inv.status = 'paid' then
    raise exception 'Invoice % is already paid.', v_inv.invoice_number using errcode = '42501';
  end if;
  select coalesce(sum(amount_cents), 0) into v_paid from public.payments where invoice_id = new.invoice_id;
  if new.amount_cents > v_inv.total_cents - v_paid then
    raise exception 'That''s more than the $% still due on %.',
      to_char((v_inv.total_cents - v_paid) / 100.0, 'FM999999990.00'), v_inv.invoice_number
      using errcode = 'P0001';
  end if;
  -- Stripe's card link is for the full amount and stays payable until the
  -- invoice is paid, so a part payment there would let the customer pay twice.
  if v_inv.stripe_invoice_id is not null and new.amount_cents < v_inv.total_cents - v_paid then
    raise exception 'Invoice % has a card link for the full amount. Record the full payment, or have the customer pay the link.',
      v_inv.invoice_number using errcode = 'P0001';
  end if;
  if new.received_on > (now() at time zone coalesce(
       (select timezone from public."Clients" where id = new.client_id), 'America/Denver'))::date then
    raise exception 'A payment can''t be dated in the future.' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

-- After a payment: a draft becomes sent on the payment date, and an invoice
-- whose payments reach its total becomes paid on the last payment's date. An
-- invoice that's already paid or void is never rewritten.
create function public.payments_apply()
  returns trigger
  language plpgsql
  set search_path = public
as $$
declare
  v_inv public.invoices%rowtype;
  v_paid bigint;
  v_last date;
begin
  select * into v_inv from public.invoices
   where id = coalesce(new.invoice_id, old.invoice_id) for update;
  if not found or v_inv.status = 'voided' then
    return null;
  end if;
  select coalesce(sum(amount_cents), 0), max(received_on) into v_paid, v_last
    from public.payments where invoice_id = v_inv.id;

  -- Only payments move an invoice into or out of paid (invoices_guard_paid).
  perform set_config('field.payment_apply', 'on', true);
  if tg_op = 'INSERT' and v_inv.status <> 'paid' then
    update public.invoices
       set status = case when v_paid >= total_cents then 'paid'
                         when status = 'draft' then 'sent'
                         else status end,
           sent_at = coalesce(sent_at, public.tenant_noon(client_id, new.received_on)),
           paid_at = case when v_paid >= total_cents then public.tenant_noon(client_id, v_last) else paid_at end
     where id = v_inv.id;
  elsif tg_op = 'DELETE' and v_inv.status = 'paid' and v_paid < v_inv.total_cents then
    -- Removing a mistyped payment reopens the invoice; it stays sent.
    update public.invoices set status = 'sent', paid_at = null where id = v_inv.id;
  end if;
  return null;
end;
$$;

-- With "Mark paid" gone, paid status and its date come only from payments:
-- people can't set status paid, take it away, or move paid_at (which dates
-- income in the P&L). Server code (no signed-in user) is exempt.
create function public.invoices_guard_paid()
  returns trigger
  language plpgsql
  set search_path = public
as $$
begin
  if auth.uid() is null or current_setting('field.payment_apply', true) = 'on' then
    return new;
  end if;
  if tg_op = 'INSERT' then
    if new.status = 'paid' or new.paid_at is not null then
      raise exception 'Record a payment to mark an invoice paid.' using errcode = '42501';
    end if;
  elsif (new.status = 'paid') is distinct from (old.status = 'paid') or new.paid_at is distinct from old.paid_at then
    raise exception 'Paid status comes from payments: record or remove a payment instead.' using errcode = '42501';
  end if;
  return new;
end;
$$;

revoke execute on function public.payments_guard() from public, anon, authenticated, service_role;
revoke execute on function public.payments_apply() from public, anon, authenticated, service_role;
revoke execute on function public.invoices_guard_paid() from public, anon, authenticated, service_role;

create trigger invoices_guard_paid
  before insert or update on public.invoices
  for each row execute function public.invoices_guard_paid();

create trigger payments_guard
  before insert on public.payments
  for each row execute function public.payments_guard();
create trigger payments_apply
  after insert or delete on public.payments
  for each row execute function public.payments_apply();

-- 4. Voiding keeps the money trail ---------------------------------------------------
-- An invoice with payments recorded isn't voided (the money came in); remove
-- the payments first if they were a mistake. Otherwise the same as v096.
create or replace function public.invoice_void(p_invoice_id bigint)
  returns void
  language plpgsql
  set search_path = public
as $$
declare
  v_inv public.invoices%rowtype;
begin
  select * into v_inv from public.invoices where id = p_invoice_id for update;
  if not found then
    raise exception 'Invoice not found.' using errcode = 'P0001';
  end if;
  if v_inv.status = 'voided' then
    return;
  end if;
  if v_inv.status = 'paid' then
    raise exception 'A paid invoice can''t be voided.' using errcode = '42501';
  end if;
  if v_inv.status = 'draft' and v_inv.stripe_invoice_id is null then
    raise exception 'An unsent draft is deleted, not voided.' using errcode = '42501';
  end if;
  if exists (select 1 from public.payments where invoice_id = p_invoice_id) then
    raise exception 'Invoice % has payments recorded. Remove them first if they were a mistake.', v_inv.invoice_number
      using errcode = '42501';
  end if;

  update public.tasks set invoice_id = null where invoice_id = p_invoice_id;
  update public.expenses set invoiced_on = null where invoiced_on = p_invoice_id;
  update public.invoices
     set status = 'voided', voided_at = now(), updated_at = now()
   where id = p_invoice_id;
end;
$$;
revoke execute on function public.invoice_void(bigint) from public, anon, authenticated, service_role;
grant execute on function public.invoice_void(bigint) to service_role;

