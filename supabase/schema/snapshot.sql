-- Schema snapshot generator.
--
-- Read-only. Emits the DDL needed to rebuild the app's schema on a fresh
-- Supabase project: everything in `public`, plus the pieces the app owns in
-- platform schemas (storage.objects policies, storage bucket config, the
-- auth.users trigger, the supabase_realtime publication tables).
-- Supabase-managed objects (auth/storage/realtime internals, event
-- triggers, supabase_admin default privileges) are left to the platform.
--
-- Used to produce supabase/schema/prod.sql when pg_dump / `supabase db dump`
-- isn't available. Run it with any SQL client against the project and join
-- the `txt` column in (sec, sub, k) order with blank lines between rows.
-- Prefer `supabase db dump --schema public` when you have the DB password.

with
tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
),
fn as (
  select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) args,
         (select string_agg(case when a.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(a.grantee)) end,
                            ',' order by a.grantee, a.privilege_type)
          from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
          where a.grantee <> p.proowner and a.privilege_type = 'EXECUTE') sig
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d
                    where d.objid = p.oid and d.deptype = 'e')
),
rel as (
  select c.oid, c.relname, c.relkind,
         (select string_agg(a.grantee::regrole::text || ':' || a.privilege_type || ':' || a.is_grantable::text,
                            ',' order by a.grantee, a.privilege_type)
          from aclexplode(c.relacl) a where a.grantee <> c.relowner) sig
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'v', 'S')
),
heads(sec, title) as (values
  (1, 'Extensions'), (2, 'Sequences'), (3, 'Tables'), (4, 'Sequence ownership'),
  (5, 'Functions'), (6, 'Column defaults'), (7, 'Constraints'), (8, 'Views'),
  (9, 'Indexes'), (10, 'Triggers'), (11, 'Row level security'), (12, 'Policies'),
  (13, 'Privileges'), (14, 'Default privileges'), (15, 'Comments'),
  (16, 'Realtime publication'), (17, 'Storage buckets')
),
out(sec, sub, k, txt) as (
  select sec, -1, '', '-- ' || repeat('=', 74) || E'\n-- ' || title || E'\n-- ' || repeat('=', 74)
  from heads

  union all
  select 1, 0, e.extname,
         format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;',
                e.extname, e.extnamespace::regnamespace::text)
  from pg_extension e where e.extname <> 'plpgsql'

  union all
  select 2, 0, s.relname,
         format('CREATE SEQUENCE public.%I AS %s START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s%s;',
                s.relname, format_type(q.seqtypid, null), q.seqstart, q.seqincrement,
                q.seqmin, q.seqmax, q.seqcache, case when q.seqcycle then ' CYCLE' else '' end)
  from pg_class s join pg_namespace n on n.oid = s.relnamespace
  join pg_sequence q on q.seqrelid = s.oid
  where n.nspname = 'public' and s.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = s.oid and d.deptype = 'i')

  union all
  select 3, 0, t.relname,
         format(E'CREATE TABLE public.%I (\n%s\n);', t.relname,
           (select string_agg(format('    %I %s%s%s', a.attname,
                     format_type(a.atttypid, a.atttypmod),
                     case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY'
                                        when 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
                                        else '' end,
                     case when a.attnotnull then ' NOT NULL' else '' end),
                   E',\n' order by a.attnum)
            from pg_attribute a
            where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tbl t

  union all
  select 4, 0, s.relname,
         format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', s.relname, c.relname, a.attname)
  from pg_class s join pg_namespace n on n.oid = s.relnamespace
  join pg_depend d on d.objid = s.oid and d.classid = 'pg_class'::regclass
                  and d.refclassid = 'pg_class'::regclass and d.deptype = 'a'
  join pg_class c on c.oid = d.refobjid
  join pg_attribute a on a.attrelid = c.oid and a.attnum = d.refobjsubid
  where n.nspname = 'public' and s.relkind = 'S'

  union all
  select 5, 0, f.proname || '(' || f.args || ')', rtrim(pg_get_functiondef(f.oid), E'\n') || ';'
  from fn f

  union all
  select 6, 0, t.relname || '.' || a.attname,
         format('ALTER TABLE ONLY public.%I ALTER COLUMN %I SET DEFAULT %s;',
                t.relname, a.attname, pg_get_expr(d.adbin, d.adrelid))
  from tbl t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum

  union all
  select 8, 0, c.relname,
         format(E'CREATE VIEW public.%I%s AS\n%s', c.relname,
                case when c.reloptions is not null
                     then ' WITH (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
                pg_get_viewdef(c.oid))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'

  union all
  select 7, case when con.contype = 'f' then 1 else 0 end, t.relname || '.' || con.conname,
         format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;',
                t.relname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join tbl t on t.oid = con.conrelid
  where con.contype in ('p', 'u', 'c', 'f', 'x')

  union all
  select 9, 0, i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x join pg_class i on i.oid = x.indexrelid
  join tbl t on t.oid = x.indrelid
  where not exists (select 1 from pg_constraint con
                    where con.conindid = x.indexrelid and con.contype in ('p', 'u', 'x'))

  union all
  select 10, case when n.nspname = 'public' then 0 else 1 end,
         n.nspname || '.' || c.relname || '.' || tg.tgname,
         pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = tg.tgfoid
  where not tg.tgisinternal
    and (n.nspname = 'public'
         or (n.nspname = 'auth' and p.pronamespace = 'public'::regnamespace))

  union all
  select 11, 0, t.relname,
         format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
         || case when t.relforcerowsecurity
                 then format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', t.relname)
                 else '' end
  from tbl t where t.relrowsecurity

  union all
  select 12, case when n.nspname = 'public' then 0 else 1 end,
         n.nspname || '.' || c.relname || '.' || p.polname,
         format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
                p.polname, n.nspname, c.relname,
                case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
                case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT'
                              when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
                (select string_agg(case when r = 0 then 'public' else quote_ident(pg_get_userbyid(r)) end,
                                   ', ' order by o)
                 from unnest(p.polroles) with ordinality u(r, o)),
                case when p.polqual is not null
                     then E'\n  USING (' || pg_get_expr(p.polqual, p.polrelid) || ')' else '' end,
                case when p.polwithcheck is not null
                     then E'\n  WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')' else '' end)
  from pg_policy p join pg_class c on c.oid = p.polrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
     or (n.nspname = 'storage' and c.relname = 'objects')

  union all
  select 13, case g.relkind when 'S' then 1 else 0 end, g.first,
         format(E'REVOKE ALL ON %s\n    %s\n  FROM PUBLIC, anon, authenticated, service_role;', g.kw, g.list)
         || coalesce((select string_agg(
                 format(E'\nGRANT %s ON %s\n    %s\n  TO %s%s;', p.privs, g.kw, g.list, p.who,
                        case when p.grantable then ' WITH GRANT OPTION' else '' end),
                 '' order by p.who, p.grantable)
              from (select case when a.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(a.grantee)) end who,
                           a.is_grantable grantable,
                           case when count(*) = case g.relkind when 'S' then 3 else 8 end then 'ALL'
                                else string_agg(a.privilege_type, ', ' order by a.privilege_type) end privs
                    from pg_class c cross join lateral aclexplode(c.relacl) a
                    where c.oid = g.rep and a.grantee <> c.relowner
                    group by 1, 2) p), '')
  from (select r.relkind, case r.relkind when 'S' then 'SEQUENCE' else 'TABLE' end kw,
               (array_agg(r.oid))[1] rep,
               min(r.relname collate "C") first,
               string_agg(format('public.%I', r.relname), E',\n    ' order by r.relname collate "C") list
        from rel r group by 1, 2, r.sig) g

  union all
  select 13, 2, g.first,
         format(E'REVOKE ALL ON FUNCTION\n    %s\n  FROM PUBLIC, anon, authenticated, service_role;', g.list)
         || coalesce((select string_agg(format(E'\nGRANT EXECUTE ON FUNCTION\n    %s\n  TO %s;', g.list, w), ''
                                        order by w collate "C")
                      from unnest(string_to_array(g.sig, ',')) w), '')
  from (select f.sig, min(f.proname collate "C") first,
               string_agg(format('public.%I(%s)', f.proname, f.args), E',\n    '
                          order by f.proname collate "C", f.args collate "C") list
        from fn f group by f.sig) g

  union all
  select 14, 0, d.defaclobjtype::text || ':' || pg_get_userbyid(a.grantee),
         format('ALTER DEFAULT PRIVILEGES FOR ROLE %I IN SCHEMA public GRANT %s ON %s TO %s;',
                pg_get_userbyid(d.defaclrole),
                string_agg(a.privilege_type, ', ' order by a.privilege_type),
                case d.defaclobjtype when 'r' then 'TABLES' when 'S' then 'SEQUENCES'
                                     when 'f' then 'FUNCTIONS' when 'T' then 'TYPES' else 'SCHEMAS' end,
                case when a.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(a.grantee)) end)
  from pg_default_acl d cross join lateral aclexplode(d.defaclacl) a
  where d.defaclnamespace = 'public'::regnamespace
    and pg_get_userbyid(d.defaclrole) = 'postgres'
  group by d.defaclrole, d.defaclobjtype, a.grantee

  union all
  select 15, 0, c.relname || '.' || coalesce(a.attname, ''),
         case when d.objsubid = 0
              then format('COMMENT ON %s public.%I IS %L;',
                          case c.relkind when 'v' then 'VIEW' when 'S' then 'SEQUENCE' else 'TABLE' end,
                          c.relname, d.description)
              else format('COMMENT ON COLUMN public.%I.%I IS %L;', c.relname, a.attname, d.description) end
  from pg_description d join rel c on c.oid = d.objoid and d.classoid = 'pg_class'::regclass
  left join pg_attribute a on a.attrelid = c.oid and a.attnum = d.objsubid and d.objsubid > 0

  union all
  select 15, 1, f.proname || '(' || f.args || ')',
         format('COMMENT ON FUNCTION public.%I(%s) IS %L;', f.proname, f.args, d.description)
  from pg_description d join fn f on f.oid = d.objoid and d.classoid = 'pg_proc'::regclass

  union all
  select 15, 2, n.nspname || '.' || c.relname || '.' || p.polname,
         format('COMMENT ON POLICY %I ON %I.%I IS %L;', p.polname, n.nspname, c.relname, d.description)
  from pg_description d join pg_policy p on p.oid = d.objoid and d.classoid = 'pg_policy'::regclass
  join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public', 'storage')

  union all
  select 15, 3, c.relname || '.' || tg.tgname,
         format('COMMENT ON TRIGGER %I ON %I.%I IS %L;', tg.tgname, n.nspname, c.relname, d.description)
  from pg_description d join pg_trigger tg on tg.oid = d.objoid and d.classoid = 'pg_trigger'::regclass
  join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public', 'auth')

  union all
  select 15, 4, t.relname || '.' || con.conname,
         format('COMMENT ON CONSTRAINT %I ON public.%I IS %L;', con.conname, t.relname, d.description)
  from pg_description d join pg_constraint con on con.oid = d.objoid and d.classoid = 'pg_constraint'::regclass
  join tbl t on t.oid = con.conrelid

  union all
  select 16, 0, pt.tablename,
         format('ALTER PUBLICATION supabase_realtime ADD TABLE ONLY %I.%I;', pt.schemaname, pt.tablename)
  from pg_publication_tables pt
  where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'

  union all
  select 17, 0, b.id,
         format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %s, %s) ON CONFLICT (id) DO NOTHING;',
                b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'NULL'),
                coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL'))
  from storage.buckets b
)
select sec, sub, k, txt from out
order by sec, sub, k collate "C"
